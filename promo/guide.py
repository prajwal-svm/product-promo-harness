"""ANIMATION_GUIDE.md: the verbatim brief every scene subagent works from."""

from __future__ import annotations

import json
import re
from pathlib import Path

from promo.config import packs_dir
from promo.packs import Pack
from promo.proc import atomic_path
from promo.run import RunPaths

GOTCHAS = """- An `<audio>` element without an `id` is never mixed (silent render).
- Register `window.__timelines["<shot-id>"]` last, after `await PromoStage.load(...)`; a wrong or early key freezes the render at t=0.
- A CSS `transform` plus a GSAP tween on the same property is a lint error; centre with flex or `xPercent`.
- Never tween `visibility`, `display` or `autoAlpha` on a clip; never `repeat: -1`.
- A clip is visible for `[start, start+duration)`: land end states a frame early.
- Stacked echo text needs `data-layout-allow-overlap` on the echo layer only.
- Shader transitions and HDR clear the root background: paint the stage on a child element.
- 3D backfaces are slow; budget them (see the cost budget)."""

HELPERS = """- `const S = await PromoStage.load("<shot-id>")` → `S.shot`, `S.chapter` (headline, key), `S.events` (each with `t_local`),
  `S.words` (`{text, t, end, line}` in shot-local seconds), `S.duration`, `S.lagS`, `S.design`.
- `PromoStage.eventsOf(S, kind)`, `PromoStage.splitWords(el, text, key)`, `PromoStage.finish(tl, S)` (grain; call once).
- `PromoMotion.ease("snappy" | "default" | "heavy" | "playful")` → a GSAP ease with `.duration`; `PromoMotion.track`,
  `PromoMotion.indicator`, `PromoMotion.swapAlpha`, `PromoMotion.rng(seed)`, `PromoMotion.loopT`."""

RULES = """- Edit only your own shot files: `scenes/shots/<your shot ids>.html`. Everything else is read-only. If a shared file
  (lib/, assets/, timing.json, design.json) is wrong, report it; do not edit it.
- Never type a time. Every moment comes from `S.events`, `S.words` or `S.duration`.
- Start from `scenes/shots/_shot-basic.html` in the harness template or your existing file; keep the root element's
  `data-composition-id` equal to the shot id.
- No blur of anything: no blur filter, no depth of field, no motion blur, no `backdrop-filter`. Seams use cuts, whips
  without blur, pushes or match moves.
- Cost budget per frame: no more than one three.js scene per shot.
- Render your shots with `promo scenes --shot <id>` and look at `promo scenes --stills` before you report back.
- Do not copy the reference's content, logos or characters; take its grammar."""


def write_guide(run: RunPaths, pack: Pack) -> Path:
    from promo.scenes import design_for

    core = packs_dir() / "_core"
    allowed = pack.allowed()
    rows = re.findall(r"^\| ([a-z0-9-]+) \| (.+?) \|$", (core / "banned.md").read_text(), flags=re.M)
    banned = [f"- `{i}`: {d}" for i, d in rows if i != "id" and i not in allowed]
    realloc = [f"- `{i}`: {reason}" for i, reason in allowed.items()]
    pack_md = (pack.root / "pack.md").read_text() if (pack.root / "pack.md").exists() else f"# {pack.name}\n"
    design = design_for(run, pack)
    parts = [
        f"# ANIMATION_GUIDE for this run (pack `{pack.name}`)",
        "Generated by `promo guide`. Pasted verbatim; do not paraphrase it when briefing others.",
        "## Rules for scene work", RULES,
        (core / "doctrine.md").read_text().strip(),
        "## Banned for this run", "\n".join(banned),
        "## Re-allowed by this pack", "\n".join(realloc or ["- (none)"]),
        pack_md.strip(),
        "## Design tokens (design.json)", f"```json\n{json.dumps(design, indent=2)}\n```",
        "## HyperFrames gotchas", GOTCHAS,
        "## Helpers available in every shot", HELPERS,
    ]
    with atomic_path(run.guide) as tmp:
        tmp.write_text("\n\n".join(parts) + "\n")
    return run.guide
